import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { execFileSync } from 'node:child_process';

const root = new URL('./', import.meta.url);
const schema = JSON.parse(await readFile(new URL('proto/ipc.schema.json', root), 'utf8'));
let go = '// Code generated by contracts/generate.mjs; DO NOT EDIT.\npackage contracts\n';
let ts = '// Code generated by contracts/generate.mjs; DO NOT EDIT.\n';
function fieldTypes(field) {
  if (field.$ref) {
    const name = field.$ref.replace('#/$defs/', '');
    return [name, name];
  }
  if (field.type === 'array') {
    const [goType, tsType] = fieldTypes(field.items);
    return [`[]${goType}`, `Array<${tsType}>`];
  }
  if (field.type === 'number') return ['float64', 'number'];
  if (field.type === 'integer') return ['int', 'number'];
  if (field.type === 'boolean') return ['bool', 'boolean'];
  if (field.type === 'string')
    return [
      'string',
      field.const
        ? JSON.stringify(field.const)
        : (field.enum?.map(JSON.stringify).join(' | ') ?? 'string'),
    ];
  throw new Error(`Unsupported field type: ${field.type}`);
}
for (const [name, definition] of Object.entries(schema.$defs)) {
  go += `\ntype ${name} struct {\n`;
  ts += `\nexport interface ${name} {\n`;
  for (const [key, field] of Object.entries(definition.properties)) {
    if (!definition.required.includes(key)) throw new Error('Optional fields are not supported');
    const [goType, tsType] = fieldTypes(field);
    go += `  ${key[0].toUpperCase() + key.slice(1)} ${goType} \`json:"${key}"\`\n`;
    ts += `  ${key}: ${tsType};\n`;
  }
  go += '}\n';
  ts += '}\n';
}
go = execFileSync('gofmt', { input: go, encoding: 'utf8' });
for (const [path, content] of [
  ['go/ipc.gen.go', go],
  ['ts/ipc.gen.ts', ts],
]) {
  const target = new URL(path, root);
  if (process.argv.includes('--check')) {
    if ((await readFile(target, 'utf8')) !== content) throw new Error(`Stale contract: ${path}`);
  } else {
    await mkdir(new URL('./', target), { recursive: true });
    await writeFile(target, content);
  }
}
