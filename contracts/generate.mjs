function csType(field) {
  if (field.anyOf) {
    const value = field.anyOf.find((option) => option.$ref);
    return `${csType(value)}?`;
  }
  if (Array.isArray(field.type)) {
    const inner = field.type.find((type) => type !== 'null');
    return `${csType({ ...field, type: inner })}?`;
  }
  if (field.$ref) {
    const name = field.$ref.replace('#/$defs/', '');
    const scalar = scalarDefinition(name);
    return scalar ? csType(scalar) : name;
  }
  if (field.type === 'array') return `${csType(field.items)}[]`;
  return { string: 'string', number: 'double', integer: 'int', boolean: 'bool' }[field.type];
}
function fieldTypes(field) {
  if (field.anyOf) {
    const value = field.anyOf.find((option) => option.$ref);
    const [goType, tsType] = fieldTypes(value);
    return [goType, `${tsType} | null`];
  }
  if (Array.isArray(field.type)) {
    const inner = field.type.find((type) => type !== 'null');
    const [goType, tsType] = fieldTypes({ ...field, type: inner });
    return [goType, `${tsType} | null`];
  }
  if (field.$ref) {
    const name = field.$ref.replace('#/$defs/', '');
    const scalar = scalarDefinition(name);
    return scalar ? fieldTypes(scalar) : [name, name];
  }
  if (field.type === 'array') {
    const [goType, tsType] = fieldTypes(field.items);
    return [`[]${goType}`, `Array<${tsType}>`];
  }
  if (field.type === 'number') return ['float64', 'number'];
  if (field.type === 'integer') return ['int', 'number'];
  if (field.type === 'boolean') return ['bool', 'boolean'];
  if (field.type === 'string')
    return [
      'string',
      field.const
        ? JSON.stringify(field.const)
        : (field.enum?.map(JSON.stringify).join(' | ') ?? 'string'),
    ];
  throw new Error(`Unsupported field type: ${field.type}`);
}
