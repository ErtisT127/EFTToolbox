import { displayNotices, redistributed, thirdParty } from '../config/third-party.mjs';

// Code-unit order on the lowercased name, so the list reads the same everywhere and names that start
// with punctuation (.NET) stay at the top where a reader expects them.
const byName = (a, b) => (a.name.toLowerCase() < b.name.toLowerCase() ? -1 : 1);

const entryLine = (entry) =>
  `- ${entry.name} — ${entry.license} — ${entry.url}${entry.note ? ` (${entry.note})` : ''}`;

/** The About page's thanks list, sorted A-Z. */
export const thanksEntries = () => [...thirdParty].sort(byName);

/** Everything the shipped notices have to cover: the thanks list plus redistributed data. */
export const noticesEntries = () => [...thirdParty, ...redistributed].sort(byName);

export function noticesText() {
  return (
    [
      'EFT Toolbox ships the following third-party software and data.',
      '',
      ...noticesEntries().map(entryLine),
      '',
      'Display resources',
      ...displayNotices,
    ].join('\n') + '\n'
  );
}

export function thirdPartyModuleText() {
  const entries = thanksEntries()
    .map(
      (entry) =>
        `  { name: ${JSON.stringify(entry.name)}, license: ${JSON.stringify(entry.license)}, url: ${JSON.stringify(entry.url)} },`,
    )
    .join('\n');
  return `// Code generated by scripts/generate-third-party.mjs; DO NOT EDIT.\nexport const thirdParty = [\n${entries}\n] as const;\n`;
}
