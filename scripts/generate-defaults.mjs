import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { execFileSync } from 'node:child_process';
import { defaults } from './config/defaults.mjs';

const root = new URL('../', import.meta.url);
const json = (value) => JSON.stringify(value);

// The generated defaults carry the contents of these data files, never a runtime path reference.
const readDataFile = async (path) => {
  try {
    return await readFile(new URL(path, root), 'utf8');
  } catch {
    throw new Error(`Missing default data file: ${path}`);
  }
};
const stunHosts = async (file) => {
  const servers = [];
  for (const line of (await readDataFile(`data/upstream/${file}`)).split('\n')) {
    const entry = line.trim().replace(/^stun:/, '');
    if (entry && !entry.startsWith('#') && !servers.includes(entry)) servers.push(entry);
  }
  return servers;
};
// The panel offers two server sources: DNS hostnames and IP literals (IPv4 + IPv6). Only the
// literal list carries IPv6; the NAT-check list stays IPv4-only because NAT is an IPv4 concept.
const stunHostServers = await stunHosts('stun-valid-hosts.txt');
const stunIP4Servers = await stunHosts('stun-valid-ipv4s.txt');
const stunIP6Servers = await stunHosts('stun-valid-ipv6s.txt');
const stunIPServers = [
  ...stunIP4Servers,
  ...stunIP6Servers.filter((s) => !stunIP4Servers.includes(s)),
];
const stunNatServers = await stunHosts('stun-nat-ipv4s.txt');
const calibrationDocuments = JSON.parse(
  await readDataFile('data/user/calibration/maps.calibration.json'),
);
const go = `// Code generated by scripts/generate-defaults.mjs; DO NOT EDIT.
package defaults

import (
  "encoding/json"
  "efttoolbox/contracts"
)

func decode[T any](data string) T { var value T; if err := json.Unmarshal([]byte(data), &value); err != nil { panic(err) }; return value }
${[
  ['UserSettings', 'UserSettings', defaults.userSettings],
  ['ItemsSettings', 'ItemsSettings', defaults.itemsSettings],
  ['MapPreferences', 'Preferences', defaults.mapPreferences],
  ['MarkerPreferences', 'MarkerPreferences', defaults.markerPreferences],
  ['CalibratorPreferences', 'CalibratorPreferences', defaults.calibratorPreferences],
  ['CalibrationDocument', 'CalibrationDocument', defaults.calibrationDocument],
  ['CalibrationDocuments', 'CalibrationDocuments', calibrationDocuments],
  ['MultiplayerSettings', 'MultiplayerSettings', defaults.multiplayerSettings],
]
  .map(
    ([name, type, value]) =>
      `func ${name}() contracts.${type} { return decode[contracts.${type}](${json(json(value))}) }`,
  )
  .join('\n')}
func StunHostServers() []string { return decode[[]string](${json(json(stunHostServers))}) }
func StunIPServers() []string { return decode[[]string](${json(json(stunIPServers))}) }
func StunNatServers() []string { return decode[[]string](${json(json(stunNatServers))}) }
`;
const goFormatted = execFileSync('gofmt', { input: go, encoding: 'utf8' });
const cs = `// Code generated by scripts/generate-defaults.mjs; DO NOT EDIT.
using System.Text.Json;
using EFTToolbox.Contracts;
namespace EFTToolbox.Overlay;
internal static class DefaultsValues {
  internal static OverlaySettings Overlay => JsonSerializer.Deserialize<OverlaySettings>(${json(json(defaults.userSettings.overlay))}, OverlaySettingsStore.Json)!;
  internal static RecognitionSettings Recognition => JsonSerializer.Deserialize<RecognitionSettings>(${json(json(defaults.userSettings.recognition))}, OverlaySettingsStore.Json)!;
}
`;
const ts = `// Code generated by scripts/generate-defaults.mjs; DO NOT EDIT.
export const mapPreferences = ${json(defaults.mapPreferences)} as const;
export const markerPreferences = ${json(defaults.markerPreferences)} as const;
export const calibratorPreferences = ${json(defaults.calibratorPreferences)} as const;
export const defaultGroups: readonly string[] = ${json(defaults.defaultGroups)};
`;
const outputs = [
  ['backend/internal/defaults/defaults.gen.go', goFormatted],
  ['overlay/src/app/Defaults.g.cs', cs],
  ['dashboard/src/defaults.gen.ts', ts],
];
for (const [path, content] of outputs) {
  const target = new URL(path, root);
  if (process.argv.includes('--check')) {
    if ((await readFile(target, 'utf8')) !== content) throw new Error(`Stale defaults: ${path}`);
  } else {
    await mkdir(new URL('./', target), { recursive: true });
    await writeFile(target, content);
  }
}
